/**
 * 성경 권과 장에 따른 요약 및 핵심 정보 반환
 */
function getChapterInfo(bookName, chapter) {
  const bookData = BIBLE_SUMMARIES[bookName];
  if (bookData && bookData.chapters && bookData.chapters[chapter]) {
    return {
      bookName,
      chapter,
      ...bookData.chapters[chapter]
    };
  }

  // 기본 Fallback 생성기 (데이터가 상세히 작성되지 않은 권·장일 경우 신학적 정형 데이터 생성)
  return {
    bookName,
    chapter,
    title: `${bookName} ${chapter}장 말씀`,
    summary: `${bookName} ${chapter}장을 통해 우리 삶의 주관자이신 하나님의 크신 뜻과 언약 백성을 향한 구속의 사랑을 묵상합니다.`,
    verse: `${bookName} ${chapter}장 본문 중에서 마음에 와닿는 귀한 한 구절을 조용히 소리 내어 묵상해 보세요.`,
    meditation: "말씀 앞에 나를 비추어 보고, 오늘 하루 주님의 뜻에 합당한 삶의 열매를 맺어가기를 결단합니다."
  };
}

/**
 * 특정 범위(3장)의 통합 묵상 메시지 패키지 생성
 */
function generateDailyPassagePackage(chaptersList) {
  if (!chaptersList || chaptersList.length === 0) return null;

  const first = chaptersList[0];
  const last = chaptersList[chaptersList.length - 1];
  const isSameBook = first.book.id === last.book.id;

  const passageTitle = isSameBook
    ? `${first.book.name} ${first.chapter}장 - ${last.chapter}장`
    : `${first.book.name} ${first.chapter}장 - ${last.book.name} ${last.chapter}장`;

  const chapterDetails = chaptersList.map(item => {
    return getChapterInfo(item.book.name, item.chapter);
  });

  // 대표 구절 (중간 또는 첫 번째 장의 대표 구절 활용)
  const keyVerseItem = chapterDetails.find(c => c.verse && !c.verse.includes("소리 내어")) || chapterDetails[0];

  return {
    passageTitle,
    chaptersCount: chaptersList.length,
    chapterDetails,
    keyVerse: keyVerseItem.verse,
    keyMeditation: keyVerseItem.meditation,
    summaryBullets: chapterDetails.map(c => `• [${c.bookName} ${c.chapter}장] ${c.summary}`)
  };
}
