/**
 * 성경 권과 장에 따른 요약 반환 (Fallback 포함)
 */
function getChapterInfo(bookName, chapter) {
  const bookData = BIBLE_SUMMARIES[bookName];
  if (bookData && bookData.chapters && bookData.chapters[chapter]) {
    return {
      bookName,
      chapter,
      title: bookData.chapters[chapter].title,
      summary: bookData.chapters[chapter].summary
    };
  }

  return {
    bookName,
    chapter,
    title: `${bookName} ${chapter}장 말씀`,
    summary: `${bookName} ${chapter}장을 통해 우리 삶의 주관자이신 하나님의 크신 뜻과 언약 백성을 향한 구속의 사랑을 묵상합니다.`
  };
}
