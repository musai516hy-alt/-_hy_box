/**
 * 성경 권과 장에 따른 요약 및 핵심 정보 반환 (스마트 폴백 엔진 포함)
 */
function getChapterInfo(bookName, chapter) {
  const bookData = BIBLE_SUMMARIES[bookName];
  if (bookData && bookData.chapters && bookData.chapters[chapter]) {
    const chInfo = bookData.chapters[chapter];
    return {
      bookName,
      chapter,
      title: chInfo.title,
      summary: chInfo.summary,
      verse: chInfo.verse || `${bookName} ${chapter}장 말씀 중에서 마음에 와닿는 구절을 조용히 묵상해 보세요.`,
      meditation: chInfo.meditation || `${bookName} ${chapter}장의 말씀을 통해 오늘 하루 나에게 말씀하시는 하나님의 뜻을 구합니다.`
    };
  }

  // 66권 범용 스마트 Fallback 해설기 (객관적 말씀 줄거리)
  return {
    bookName,
    chapter,
    title: `${bookName} ${chapter}장 말씀`,
    summary: `${bookName} ${chapter}장의 주요 기록과 말씀입니다.`
  };
}

/**
 * 연속된 장 목록(예: 3장)의 통합 묵상 패키지 생성
 */
function generateDailyPassagePackage(chaptersList) {
  if (!chaptersList || chaptersList.length === 0) return null;

  const first = chaptersList[0];
  const last = chaptersList[chaptersList.length - 1];
  const isSameBook = first.book.id === last.book.id;

  const passageTitle = isSameBook
    ? `${first.book.name} ${first.chapter}장 - ${last.chapter}장`
    : `${first.book.name} ${first.chapter}장 - ${last.book.name} ${last.chapter}장`;

  const passageAbbr = isSameBook
    ? (first.chapter === last.chapter ? `${first.book.abbr} ${first.chapter}장` : `${first.book.abbr} ${first.chapter}-${last.chapter}장`)
    : `${first.book.abbr} ${first.chapter}장 - ${last.book.abbr} ${last.chapter}장`;

  const chapterDetails = chaptersList.map(item => {
    return getChapterInfo(item.book.name, item.chapter);
  });

  // 대표 묵상 구절 선택
  const keyVerseItem = chapterDetails.find(c => c.verse && !c.verse.includes("조용히 묵상") && !c.verse.includes("소리 내어")) || chapterDetails[0];

  return {
    passageTitle,
    passageAbbr,
    chaptersCount: chaptersList.length,
    chapterDetails,
    keyVerse: keyVerseItem.verse,
    keyMeditation: keyVerseItem.meditation,
    summaryBullets: chapterDetails.map(c => `• [${c.bookName} ${c.chapter}장] ${c.title} : ${c.summary}`)
  };
}

